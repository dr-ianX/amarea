function t(key, fallback = '') {
  const lang = localStorage.getItem('amarea_lang') || DEFAULT_LANG;
  const dict = I18N[lang] || I18N[DEFAULT_LANG];
  return dict[key] !== undefined ? dict[key] : (I18N[DEFAULT_LANG][key] || fallback);
}

function setLang(lang) {
  if (!I18N[lang]) lang = DEFAULT_LANG;
  localStorage.setItem('amarea_lang', lang);
  document.documentElement.lang = lang;
  translatePage();
}

function translatePage() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.dataset.i18n;
    if (I18N[DEFAULT_LANG][key]) el.textContent = t(key, el.textContent);
  });
  document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
    const key = el.dataset.i18nPlaceholder;
    if (I18N[DEFAULT_LANG][key]) el.placeholder = t(key, el.placeholder);
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const key = el.dataset.i18nTitle;
    if (I18N[DEFAULT_LANG][key]) el.title = t(key, el.title);
  });
}

document.addEventListener('DOMContentLoaded', () => {
  const saved = localStorage.getItem('amarea_lang') || DEFAULT_LANG;
  document.documentElement.lang = saved;
  translatePage();
});
